"""Generate the saturation pressure tables of R32 and R410A.

Development only: needs CoolProp (`pip install CoolProp`), which is not a
runtime dependency of the integration. The bubble point pressure is computed
with the reference equations of state of CoolProp every 0.1 K from -65 °C to
+71 °C and written as a data module.

Usage: python scripts/generate_saturation_tables.py
"""

from pathlib import Path

import CoolProp
from CoolProp.CoolProp import PropsSI

FIRST = -650  # tenths of °C
LAST = 710
OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "custom_components"
    / "daikin_heat_pump_control"
    / "uart"
    / "saturation_tables.py"
)
FLUIDS = {"R32": "R32", "R410A": "R410A"}
PER_LINE = 8


def _pressures(fluid: str) -> list[float]:
    """Return the bubble point pressure in bar(a) for every tenth of a degree."""
    return [
        round(PropsSI("P", "T", tenth / 10 + 273.15, "Q", 0, fluid) / 1e5, 4)
        for tenth in range(FIRST, LAST + 1)
    ]


def main() -> None:
    """Write the data module."""
    lines = [
        '"""Saturation (bubble point) pressure of the refrigerants.',
        "",
        "Generated by scripts/generate_saturation_tables.py with CoolProp "
        f"{CoolProp.__version__};",
        "do not edit. Pressure in bar(a) from FIRST_TEMPERATURE in steps of",
        "TEMPERATURE_STEP (°C).",
        '"""',
        "",
        "from typing import Final",
        "",
        f"FIRST_TEMPERATURE: Final = {FIRST / 10}",
        "TEMPERATURE_STEP: Final = 0.1",
        "",
    ]
    for name, fluid in FLUIDS.items():
        values = _pressures(fluid)
        lines.append(f"{name}: Final[tuple[float, ...]] = (")
        for index in range(0, len(values), PER_LINE):
            chunk = ", ".join(f"{value}" for value in values[index : index + PER_LINE])
            lines.append(f"    {chunk},")
        lines.append(")")
        lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
